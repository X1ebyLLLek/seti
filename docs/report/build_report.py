def num(x, d=1):
    if x in (None, ""):
        return "—"
    return f"{float(x):.{d}f}".replace(".", ",")


def st(scheme, metric, field="median", d=1):
    return num(STATS[(scheme, metric)][field], d)


def junit():
    root = ET.parse(os.path.join(ACC, "junit.xml")).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    per = {}
    for tc in suite.iter("testcase"):
        mod = tc.get("classname", "").split(".")[-1]
        bad = tc.find("failure") is not None or tc.find("error") is not None
        p = per.setdefault(mod, [0, 0])
        p[0] += 1
        p[1] += 0 if bad else 1
    return int(suite.get("tests")), int(suite.get("failures")) + int(suite.get("errors")), per


def series_rows(scheme, name):
    rows = []
    for run in sorted(os.listdir(os.path.join(SERIES, scheme))):
        p = os.path.join(SERIES, scheme, run, name)
        if os.path.exists(p):
            rows += read_csv(p)
    return rows


