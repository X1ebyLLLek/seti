def series_rows_prefix(scheme, name):
    rows = []
    base = os.path.join(SERIES_PREFIX, scheme)
    for run in sorted(os.listdir(base)):
        p = os.path.join(base, run, name)
        if os.path.exists(p):
            rows += read_csv(p)
    return rows


